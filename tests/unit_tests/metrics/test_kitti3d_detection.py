    classes = ["Car"]
    metric = Kitti3DMetricDet(
        current_classes=classes,
        compute_aos=True,
    )

    preds, gts = get_preds_and_gts()

    metric.update(preds, gts)
    names, values = metric.get()
    assert names is not None
    assert values is not None
    assert len(names) == len(values)
